def livery(g, slots):
    """Declare the colour slots, (name, default paint) in slot order, as the car declares its Paint slot: every paint
    is a preset of each slot. Return the defaults as stored."""
    presets = [[name, colour_text(value)] for name, value in PAINT.items()]
    g.colour_slots = [{'name': name, 'colour': colour_text(PAINT[paint]), 'presets': presets} for name, paint in slots]
    return [colour(slot['colour']) for slot in g.colour_slots]


def face(g, points, paint, slot, outward):
    """A convex polygon facing `outward`; repeated and collinear corners are dropped."""
    points = [Vector(p) for p in points]
    points = [p for i, p in enumerate(points) if (p - points[i - 1]).length > 1e-6]
    points = [p for i, p in enumerate(points)
              if (p - points[i - 1]).cross(points[(i + 1) % len(points)] - p).length > 1e-9]
    if len(points) < 3:
        return
    normal = (points[1] - points[0]).cross(points[2] - points[0])
    if normal.dot(Vector(outward)) < 0:
        points.reverse()
    # The slot in force is restored: the rail builder draws its slot blocks through chamfered().
    previous, g.slot = g.slot, slot
    g.face([tuple(p) for p in points], paint)
    g.slot = previous


def clip(polygon, z0, z1):
    """The part of a convex polygon (3D points) between two heights."""
    for level, keep in ((z0, lambda p: p.z >= z0 - 1e-9), (z1, lambda p: p.z <= z1 + 1e-9)):
        result = []
        for i, p in enumerate(polygon):
            q = polygon[(i + 1) % len(polygon)]
            if keep(p):
                result.append(p)
            if keep(p) != keep(q):
                result.append(p.lerp(q, (level - p.z) / (q.z - p.z)))
        polygon = result
        if not polygon:
            break
    return polygon


def loft(g, half, stations, paint, caps=(None, None), base=BODY):
    """A convex section swept along Y. `half` is its right half in XZ from the bottom centre (x 0) round to the top
    centre (x 0); a station (y, sx, sz) scales it about (0, base). paint(i, y0, y1) gives the (colour, slot) of the
    strip of section edge i (both halves) between two stations; a cap at the first or last station is a list of
    bands (z top in section units, colour, slot), bottom up."""
    n = len(half)
    rings = []
    for y, sx, sz in stations:
        side = [Vector((x * sx, y, base + (z - base) * sz)) for x, z in half]
        rings.append(side + [Vector((-p.x, p.y, p.z)) for p in reversed(side[1:-1])])
    count = len(rings[0])
    edge = [k if k < n - 1 else 2 * n - 3 - k for k in range(count)]
    for a, b in zip(rings, rings[1:]):
        middle = sum((p.z for p in a + b), 0) / (2 * count)
        for k in range(count):
            j = (k + 1) % count
            centre = (a[k] + a[j] + b[j] + b[k]) / 4
            face(g, [a[k], a[j], b[j], b[k]], *paint(edge[k], a[0].y, b[0].y), (centre.x, 0, centre.z - middle))
    for ring, bands, (y, sx, sz), facing in ((rings[0], caps[0], stations[0], -1), (rings[-1], caps[1], stations[-1], 1)):
        low = base + (half[0][1] - base) * sz
        for top, paint_, slot in bands or ():
            top = base + (top - base) * sz
            face(g, clip(ring, low, top), paint_, slot, (0, facing, 0))
            low = top


def prism(g, outline, a0, a1, paint, slot=0, axis='y'):
    """A convex 2D outline (u, v) extruded along `axis` from a0 to a1: (u, t, v) along Y, (t, u, v) along X."""
    a0, a1 = min(a0, a1), max(a0, a1)

    def point(u, v, t):
        return Vector((u, t, v) if axis == 'y' else (t, u, v))
    cu, cv = sum(u for u, _ in outline) / len(outline), sum(v for _, v in outline) / len(outline)
    along = point(0, 0, 1)
    for i, (u, v) in enumerate(outline):
        p, q = outline[i], outline[(i + 1) % len(outline)]
        mid = point((p[0] + q[0]) / 2 - cu, (p[1] + q[1]) / 2 - cv, 0)
        face(g, [point(*p, a0), point(*q, a0), point(*q, a1), point(*p, a1)], paint, slot, mid)
    face(g, [point(u, v, a0) for u, v in outline], paint, slot, -along)
    face(g, [point(u, v, a1) for u, v in outline], paint, slot, along)


def box(g, centre, size, paint, slot=0):
    previous, g.slot = g.slot, slot
    g.box(centre, size, paint)
    g.slot = previous


def block(g, centre, size, paint, slot=0, bevel=.12):
    """A box whose edges LOD0 bevels (chamfered)."""
    if g.detail:
        chamfered(g, centre, size, paint, slot, bevel)
    else:
        box(g, centre, size, paint, slot)


def chamfered(g, centre, size, paint, slot=0, bevel=.12):
    """A box whose twelve edges are bevelled, inside the box's own bounds: LOD0's lids, housings and boxes."""
    half = [s / 2 for s in size]

    def corner(signs, axis):
        # The corner's point on the face across `axis`: full extent along it, inset by the bevel along the others.
        return tuple(c + s * (h if k == axis else h - bevel) for k, (c, s, h) in enumerate(zip(centre, signs, half)))
    for axis in range(3):
        u, v = [k for k in range(3) if k != axis]
        for s in (-1, 1):
            signs = [[0] * 3 for _ in range(4)]
            for ring, (a, b) in zip(signs, ((1, 1), (1, -1), (-1, -1), (-1, 1))):
                ring[axis], ring[u], ring[v] = s, a, b
            face(g, [corner(r, axis) for r in signs], paint, slot, [s if k == axis else 0 for k in range(3)])
    for i, j in ((0, 1), (0, 2), (1, 2)):
        k = 3 - i - j
        for si in (-1, 1):
            for sj in (-1, 1):
                ends = []
                for sk in (-1, 1):
                    signs = [0] * 3
                    signs[i], signs[j], signs[k] = si, sj, sk
                    ends.append((corner(signs, i), corner(signs, j)))
                outward = [0] * 3
                outward[i], outward[j] = si, sj
                face(g, [ends[0][0], ends[0][1], ends[1][1], ends[1][0]], paint, slot, outward)
    for signs in ((sx, sy, sz) for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)):
        face(g, [corner(signs, axis) for axis in range(3)], paint, slot, signs)


def rod(g, a, b, width, paint, sides=4):
    g.beam(a, b, width, paint, sides)


def sides(g, x, outline, paint, slot=0):
    """A flush polygon (y, z) on both sides of the body at |x|, facing out."""
    for s in (-1, 1):
        face(g, [(s * x, y, z) for y, z in outline], paint, slot, (s, 0, 0))


def panel(g, x, y0, y1, z0, z1, paint, slot=0):
    sides(g, x, [(y0, z0), (y1, z0), (y1, z1), (y0, z1)], paint, slot)


def end_panel(g, y, x0, x1, z0, z1, paint, facing, mirrored=True):
    for s in ((-1, 1) if mirrored else (1,)):
        face(g, [(s * x0, y, z0), (s * x1, y, z0), (s * x1, y, z1), (s * x0, y, z1)], paint, 0, (0, facing, 0))


def chevron(g, x, y, z, size, paint, slot):
    """The colony emblem on both sides: a V of two bars pointing down, centred at (y, z)."""
    w, h, t = size, size * .7, size * .32
    for s in (-1, 1):
        sides(g, x, [(y + s * w, z + h), (y + s * (w - t), z + h), (y, z - h + t * .9), (y, z - h)], paint, slot)


def cylinder(g, y0, y1, z, radius, paint, slot=0, count=16):
    """A tube along Y with a flat face toward each side (no end caps)."""
    for i in range(count):
        a, b = (i - .5) * 2 * pi / count, (i + .5) * 2 * pi / count
        p, q = (radius * cos(a), radius * sin(a)), (radius * cos(b), radius * sin(b))
        middle = (p[0] + q[0], 0, p[1] + q[1])
        face(g, [(p[0], y0, z + p[1]), (q[0], y0, z + q[1]), (q[0], y1, z + q[1]), (p[0], y1, z + p[1])], paint, slot,
             middle)


def shoe(g, y, light):
    """A suspension shoe centred at y: a bridge over the guide rail under the body and two cheeks down the beam's
    sides, each with a magnet light."""
    box(g, (0, y, (HOVER + BODY) / 2), (2 * SHOE_OUT, SHOE, BODY - HOVER), DARK)
    for s in (-1, 1):
        prism(g, [(s * SHOE_IN, SHOE_LOW), (s * 3.45, SHOE_LOW), (s * SHOE_OUT, 1.85), (s * SHOE_OUT, HOVER),
                  (s * SHOE_IN, HOVER)], y - SHOE / 2, y + SHOE / 2, DARK)
    panel(g, SHOE_OUT + .05, y - 1.4, y + 1.4, 2.7, 3.2, light)
    if g.detail:
        # Three magnet modules down each cheek, a bezel round the light, the bridge's suspension brackets and a gap
        # sensor on the shoe's inner end.
        for dy in (-1.95, 1.95):
            panel(g, SHOE_OUT + .03, y + dy - .07, y + dy + .07, 1.95, HOVER - .1, shade(FRAME, 1.6))
        panel(g, SHOE_OUT + .03, y - 1.55, y + 1.55, 2.55, 3.35, FRAME)
        for dy in (-1.6, 1.6):
            panel(g, SHOE_OUT + .03, y + dy - .45, y + dy + .45, HOVER + .06, BODY - .06, FRAME)
        inner = y - (1 if y > 0 else -1) * (SHOE / 2 + .2)
        for s in (-1, 1):
            box(g, (s * 3.2, inner, 3.0), (.7, .4, 1.0), FRAME)


def running_gear(g, light, drawbars=(-1, 1)):
    """Both shoes, the underframe between them and a drawbar at each coupled end."""
    at = LENGTH / 2 - .3 - SHOE / 2
    for s in (-1, 1):
        shoe(g, s * at, light)
    box(g, (0, 0, (HOVER + BODY) / 2 + .05), (6.6, 2 * (at - SHOE / 2) - .2, BODY - HOVER - .1), FRAME)
    for s in drawbars:
        box(g, (0, s * (LENGTH / 2 + GAP / 4 - .5), 4.95), (1.1, GAP / 2 + 1, .7), DARK)
    if g.detail:
        # Underfloor equipment beside the beam and clear of it, with cooling fins, and the drawbars' coupler heads.
        for y0, y1 in ((-8.4, -3.3), (-2.5, 2.5), (3.3, 8.4)):
            for s in (-1, 1):
                chamfered(g, (s * 3.15, (y0 + y1) / 2, 3.95), (1.1, y1 - y0, 1.1), FRAME, 0, .12)
            for k in range(1, round(y1 - y0) * 2):
                panel(g, 3.72, y0 + k * .5 - .07, y0 + k * .5 + .07, 3.6, 4.3, DARK)
        for s in drawbars:
            chamfered(g, (0, s * (LENGTH / 2 + GAP / 2 - .4), 4.95), (1.6, .8, .9), DARK, 0, .15)


def ladder(g, x, y, z0, z1, rungs, paint):
    """LOD0: a ladder up an end face at y, its rails at x and x + 0.8."""
    for u in (x, x + .8):
        rod(g, (u, y, z0), (u, y, z1), .14, paint)
    for k in range(1, rungs + 1):
        z = z0 + (z1 - z0) * k / (rungs + 1)
        rod(g, (x, y, z), (x + .8, y, z), .1, paint)


