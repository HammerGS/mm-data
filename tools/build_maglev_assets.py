def draw(function, detail=False):
    """A piece drawn at one level: with detail its LOD0 (function adds the close-up detail where g.detail is set),
    without it the plain LOD1, or the only level of a piece without detail."""
    mesh = Mesh()
    mesh.detail = detail
    function(mesh)
    return mesh


def export_levels(asset, levels):
    """export_mesh for a vehicle's levels {0: detailed, 1: plain}: one GLB with the root groups <name>-lod0 and -lod1
    (RigidGlb.loadLods). The detail keeps the plain level's colour slots, silhouette and ride height: both levels have
    the same bounds (the client measures, picks and supports on level 0) and reach down exactly as far."""
    bounds = {level: [(min(mesh.vertices[k::12]), max(mesh.vertices[k::12])) for k in range(3)]
              for level, mesh in levels.items()}
    assert levels[0].colour_slots == levels[1].colour_slots, f'{asset}: the levels declare other colour slots'
    assert all(abs(a - b) < 2e-3 for pair0, pair1 in zip(bounds[0], bounds[1]) for a, b in zip(pair0, pair1)), \
        f'{asset}: the levels have other bounds {bounds}'
    assert abs(bounds[0][2][0] - bounds[1][2][0]) < 1e-6, f'{asset}: LOD0 rides at another height'
    write_glb(BOARD / (asset + '.glb'), levels={level: mesh.data(Path(asset).name) for level, mesh in levels.items()},
              extras={'mmColourSlots': levels[0].colour_slots})


def check(name, mesh, budget=1500):
    """Ride convention and budget: no vehicle part comes within 0.3 px of the beam or reaches the pier cap, the
    vehicles keep their length, and every piece stays within its budget (1,500 triangles, DETAIL_BUDGET at LOD0)."""
    values = mesh.vertices
    points = [values[i:i + 3] for i in range(0, len(values), 12)]
    triangles = sum(len(v) // 3 for v in mesh.parts.values())
    size = [round(max(p[k] for p in points) - min(p[k] for p in points), 2) for k in range(3)]
    low = min(p[2] for p in points)
    assert triangles <= budget, f'{name}: {triangles} triangles'
    if name == 'platform':
        assert abs(low) < 1e-6, f'{name} stands at {low}'
    else:
        assert low >= SHOE_LOW - 1e-6 and low > PIER_CAP, f'{name} reaches down to {low}'
        inside = [p for p in points if abs(p[0]) < BEAM_HALF + .3 and p[2] < RAIL_TOP + .3]
        assert not inside, f'{name} enters the beam at {inside[0]}'
        reach = max(abs(p[1]) for p in points)
        assert reach <= (GAP / 2 + .4 if name == 'coupler' else LENGTH / 2 + GAP / 2 + 1e-6), f'{name} reaches {reach}'
    return {'triangles': triangles, 'size': size, 'min_z': round(low, 3)}


def thumbnail(rows, target, scale=72):
    """A transparent 256x160 view of rows in vertex colours, the size of the editor's palette previews; scale is the
    view's width in board px."""
    scene = bpy.context.scene
    for item in list(bpy.data.objects):
        bpy.data.objects.remove(item)
    # The rows turn as one, so the vehicle lies across the image with the cab's nose to the right.
    root = bpy.data.objects.new('rows', None)
    scene.collection.objects.link(root)
    root.rotation_euler = Euler((0, 0, radians(-90)))
    for row in rows:
        holder = bpy.data.objects.new(row['asset'], None)
        scene.collection.objects.link(holder)
        holder.parent = root
        holder.location = row['position']
        holder.rotation_euler = Euler((0, 0, radians(row['rotation'])))
        holder.scale = (row['scale'],) * 3
        bpy.ops.import_scene.gltf(filepath=str(BOARD / (row['asset'] + '.glb')))
        # Every GLB's levels are root groups <name>-lodN; the thumbnail shows level 0.
        for item in [item for item in bpy.context.selected_objects if item.parent is None]:
            if '-lod0' in item.name:
                item.parent = holder
            else:
                for part in [*item.children_recursive, item]:
                    bpy.data.objects.remove(part)
    camera = bpy.data.objects.new('camera', bpy.data.cameras.new('camera'))
    scene.collection.objects.link(camera)
    camera.data.type = 'ORTHO'
    # The palette's three-quarter view: from the south-east, 40 degrees above the ground.
    camera.data.ortho_scale = scale
    camera.rotation_euler = Euler((radians(50), 0, radians(35)))
    camera.location = camera.rotation_euler.to_matrix() @ Vector((0, 0, 120))
    scene.camera = camera
    scene.render.engine = 'BLENDER_WORKBENCH'
    scene.display.shading.light = 'STUDIO'
    scene.display.shading.color_type = 'VERTEX'
    scene.render.film_transparent = True
    scene.view_settings.view_transform = 'Standard'
    scene.render.resolution_x, scene.render.resolution_y = 256, 160
    scene.render.filepath = str(target)
    bpy.ops.render.render(write_still=True)


def build():
    stats = {}
    for name, function in PIECES.items():
        if name in VEHICLES:
            levels = {0: draw(function, True), 1: draw(function)}
            stats[name] = {'lod0': check(name, levels[0], DETAIL_BUDGET), 'lod1': check(name, levels[1])}
            export_levels('scenery/maglev/' + name, levels)
        else:
            mesh = draw(function)
            stats[name] = check(name, mesh)
            export_mesh('scenery/maglev/' + name, mesh)
    layout_path = BOARD / 'scenery/layouts.json'
    compositions = json.loads(layout_path.read_text(encoding='utf-8'))
    rows = {key: [{'asset': 'scenery/maglev/' + name, 'position': [0.0, float(y), 0.0], 'rotation': 0.0, 'scale': 1.0}
                  for name, y in pieces] for key, pieces in STAMPS.items()}
    if any(compositions.get(key) != value for key, value in rows.items()):
        # A read-modify-write of these keys alone: other builders own the other keys.
        compositions = json.loads(layout_path.read_text(encoding='utf-8'))
        compositions.update(rows)
        layout_path.write_text(json.dumps(compositions, indent=2) + '\n', encoding='utf-8')
    for key, scale in THUMBNAILS.items():
        thumbnail(rows[key], BOARD / (key + '.png'), scale)
    return stats


if __name__ == '__main__':
    print(json.dumps(build()))
