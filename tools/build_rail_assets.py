def train_rows(train):
    rows, front = [], sum(LENGTH[name] for name, _ in train) / 2
    for name, rotation in train:
        rows.append({'asset': 'scenery/rail/' + name, 'position': [0.0, front - LENGTH[name] / 2, 0.0],
                     'rotation': float(rotation), 'scale': 1.0})
        front -= LENGTH[name]
    return rows


def summary(mesh):
    values = mesh.vertices
    return {'triangles': sum(len(v) // 3 for v in mesh.parts.values()),
            'size': [round(max(values[k::12]) - min(values[k::12]), 2) for k in range(3)],
            'min_z': round(min(values[2::12]), 4)}


def build():
    stats = {}
    for name, function in PIECES.items():
        if name in LENGTH:
            levels = {0: draw(function, True), 1: draw(function)}
            stats[name] = {'lod0': summary(levels[0]), 'lod1': summary(levels[1])}
            assert stats[name]['lod0']['triangles'] <= DETAIL_BUDGET, f'{name}: {stats[name]}'
            export_levels('scenery/rail/' + name, levels)
        else:
            mesh = draw(function)
            stats[name] = summary(mesh)
            export_mesh('scenery/rail/' + name, mesh)
    layout_path = BOARD / 'scenery/layouts.json'
    compositions = json.loads(layout_path.read_text(encoding='utf-8'))
    for key, train in TRAINS.items():
        compositions['scenery/rail/' + key] = train_rows(train)
    layout_path.write_text(json.dumps(compositions, indent=2) + '\n', encoding='utf-8')
    for key, train in TRAINS.items():
        # The train lies diagonally across the thumbnail, so about 0.82 of its length spans the view's width.
        thumbnail(compositions['scenery/rail/' + key], BOARD / f'scenery/rail/{key}.png',
                  sum(LENGTH[name] for name, _ in train) * .9)
    return stats


if __name__ == '__main__':
    print(json.dumps(build()))
