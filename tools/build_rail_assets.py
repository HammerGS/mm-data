def locomotive(g):
    """Frontier Rail's armoured freight locomotive, 20 m: one full-width armoured body whose skirts hang low between
    the bogies and are cut away over them, a raised cab with slit windows and a sloped armoured windscreen, a long
    armoured nose falling to a striped snow plough at +Y, a raised radiator section with grilles and fans, headlamps,
    amber beacons, and the livery: olive armour (Body), an orange stripe and chevrons (Trim)."""
    body, trim = livery(g, 'Olive', 'Orange')
    couplers(g, LENGTH['locomotive'])
    for y in (-17.5, 17.5):
        bogie(g, y, 3, 11.2)
    hull = lambda zb: armour(zb, 4.4, 9.4, (3.4, 10.8), (2.6, 11.0))
    cab = lambda zb: armour(zb, 4.4, 11.0, (4.15, 12.0), (3.2, 13.4))
    sections = [(-26.4, armour(2.8, 4.2, 9.0, (3.2, 10.2), (2.4, 10.4))), (-25.6, hull(2.8)), (-24.8, hull(3.8)),
                (-10.2, hull(3.8)), (-9.4, hull(2.4)), (7.6, hull(2.4)), (8.4, cab(2.4)), (9.4, cab(2.4)),
                (10.2, cab(3.8)), (14.4, cab(3.8)), (16.0, armour(3.8, 4.4, 10.0, (4.1, 10.6), (3.0, 11.0))),
                (24.0, armour(3.8, 4.3, 6.9, (3.7, 7.5), (2.7, 7.7))),
                (25.4, [(3.6, 3.4), (3.85, 4.0), (3.85, 5.2), (3.85, 5.8), (3.75, 6.1), (3.3, 6.4), (2.4, 6.5)])]
    # Segments 6 to 8 are the cab, 9 its windscreen, 10 and 11 the nose; bands: 0 skirt bevel, 1 side, 2 stripe,
    # 3 upper side, 4 shoulder (the cab's slit windows), 5 roof edge, 6 roof.

    def paint(k, band):
        if band == -1:
            return 0, DARK
        if band == 2:
            return 2, trim
        if (band == 4 and 6 <= k <= 8) or (k == 9 and band >= 4):
            return 0, CAB_GLASS
        return 1, shade(body, .78) if band == 0 else shade(body, .88) if band in (4, 5) else body
    loft(g, sections, paint, ((1, shade(body, .8)), (1, shade(body, .85))))
    plough(g, 24.6, 27.7, 4.3)
    end_stripes(g, -26.45, 4.0, 2.8, 4.6, 7)
    radiator = [(3.3, 10.6), (3.3, 11.8), (2.6, 12.4)]
    loft(g, [(-25.4, radiator), (-12.0, radiator)], lambda k, band: None if band == -1 else (1, shade(body, .9)),
         ((1, shade(body, .8)), (1, shade(body, .8))))
    g.slot = 0
    for x in (-3.32, 3.32):
        plate(g, x, rect(-24.6, -12.8, 10.9, 11.6), DARK)  # radiator grilles
    for x in (-4.42, 4.42):
        for y0 in (-23.6, -16.8, -1.0):
            plate(g, x, rect(y0, y0 + 5.4, 6.9, 9.0), DARK)  # side vents and their louvres
            for z in (7.5, 8.3):
                plate(g, x * 1.005, rect(y0 + .3, y0 + 5.1, z, z + .2), RUNNING)
    for y in (-21.5, -15.9):
        fan(g, y, 12.4, 1.3)
    for y in (-6.0, 1.0):
        roof_plate(g, 11.15, rect(-1.2, 1.2, y - 1.6, y + 1.6), DARK)  # roof hatches
    g.box((0, 9.4, 13.6), (1.6, 1.2, .6), RUNNING)  # sensor housing
    for x in (-2.0, 2.0):
        end_plate(g, 25.45, rect(x - .5, x + .5, 4.6, 5.2), LAMP)  # headlamps
        g.box((x * 1.35, 23.2, 7.8), (.8, .8, .6), LAMP)
        end_plate(g, -26.45, rect(x - .5, x + .5, 8.4, 8.9), SIGN_RED)  # tail lamps
        beacon(g, x * .8, 12.0, 13.4)
    beacon(g, 0, -24.2, 12.4)
    g.slot = 1
    for x in (-4.42, 4.42):
        for y, z in ((-18.4, 4.5), (-6.0, 3.1), (6.0, 3.1)):
            plate(g, x, rect(y - .06, y + .06, z, 9.3), shade(body, .7))  # armour plate joints
    g.slot = 2
    for x in (-4.43, 4.43):
        chevron(g, x, 12.4, 8.6, 1.8, trim)
        chevron(g, x, 10.4, 8.6, 1.8, trim)
    g.slot = 0
    if not g.detail:
        return
    # LOD0: hatch lids on hinges, radiator slats, more louvres and a rim round each vent, exhaust stacks, horns, the
    # sensor's lens, lamp housings and ladders up the rear corners.
    for y in (-6.0, 1.0):
        chamfered(g, (0, y, 11.17), (2.2, 3.0, .34), shade(body, .85), 1, .1)
        for x in (-.7, .7):
            g.beam((x - .3, y - 1.55, 11.22), (x + .3, y - 1.55, 11.22), .16, STEEL, 6)
    for x in (-3.34, 3.34):
        for k in range(19):
            plate(g, x, rect(-24.38 + k * .6, -24.22 + k * .6, 10.95, 11.55), RUNNING)
    for x in (-4.42, 4.42):
        for y0 in (-23.6, -16.8, -1.0):
            for z in (7.1, 7.9, 8.7):
                plate(g, x * 1.005, rect(y0 + .3, y0 + 5.1, z, z + .2), RUNNING)
            for points in (rect(y0, y0 + .15, 6.9, 9.0), rect(y0 + 5.25, y0 + 5.4, 6.9, 9.0),
                           rect(y0 + .15, y0 + 5.25, 8.92, 9.0), rect(y0 + .15, y0 + 5.25, 6.9, 6.98)):
                plate(g, x * 1.004, points, RUNNING)
    for x in (-.9, .9):
        g.cylinder(x, -13.2, 12.4, .35, .45, DARK, 8)
    for x in (-1.4, 1.4):
        g.beam((x, 10.4, 13.55), (x, 11.3, 13.55), .25, STEEL, 6)
    end_plate(g, 10.02, rect(-.5, .5, 13.45, 13.75), CAB_GLASS)
    for x in (-2.0, 2.0):
        bezel(g, 25.4, x - .5, x + .5, 4.6, 5.2)
        bezel(g, -26.4, x - .5, x + .5, 8.4, 8.9)
        g.box((x * 1.35, 23.25, 8.22), (1.0, 1.0, .1), DARK)
    for x in (-3.2, 3.2):
        ladder(g, x, -26.6, 1.2, 9.6, RUNNING, 4, (.4, 0))


def coach(g):
    """Frontier Rail's armoured transit coach, 22 m: a faceted armour body whose skirts hang low between the bogies
    and are cut away over them, slit windows between armour piers, an orange stripe (Trim), armoured doors at both
    ends, roof hatches and equipment boxes."""
    body, trim = livery(g, 'Olive', 'Orange')
    couplers(g, LENGTH['coach'])
    for y in (-21.5, 21.5):
        bogie(g, y, 2, 7)
    side = lambda zb: [(4.0, zb), (4.3, zb + .8), (4.3, 6.0), (4.3, 6.8), (4.3, 8.0), (4.25, 9.2), (4.1, 10.0),
                       (3.0, 11.4)]
    end = [(3.7, 3.0), (4.0, 3.8), (4.0, 6.0), (4.0, 6.8), (4.0, 8.0), (3.95, 9.0), (3.8, 9.7), (2.8, 10.9)]
    stations = ((-29.0, 3.0), (-27.0, 3.8), (-16.0, 3.8), (-15.2, 2.6), (15.2, 2.6), (16.0, 3.8), (27.0, 3.8),
                (29.0, 3.0))

    def paint(k, band):
        if band == -1:
            return 0, DARK
        if band == 2:
            return 2, trim
        if band == 4 and 0 < k < 8:
            return 0, CAB_GLASS
        return 1, shade(body, .8) if band in (0, 6) else body
    loft(g, [(-30.2, end)] + [(y, side(zb)) for y, zb in stations] + [(30.2, end)], paint,
         ((1, shade(body, .8)), (1, shade(body, .8))))
    g.slot = 1
    for x in (-4.34, 4.34):
        for k in range(11):
            y = -24 + k * 4.8
            plate(g, x, rect(y - .8, y + .8, 7.9, 9.3), body)  # armour piers between the window slits
        for y in (-14.4, 0, 14.4):
            plate(g, x, rect(y - .07, y + .07, 4.2, 6.0), shade(body, .7))  # panel joints
    g.slot = 0
    for x in (-4.36, 4.36):
        for y in (-27.2, 27.2):
            plate(g, x, rect(y - 1.3, y + 1.3, 4.2, 9.7), RUNNING)  # armoured doors
            plate(g, x * 1.005, rect(y - .25, y + .25, 7.8, 9.2), CAB_GLASS)
    for side in (-1, 1):
        if g.detail:
            bellows(g, min(side * 30.0, side * 31.0), max(side * 30.0, side * 31.0), 4.0, 3.5, 10.5)
        else:
            g.box((0, side * 30.5, 7.0), (4.0, 1.0, 7.0), DARK)  # gangways
        end_stripes(g, side * 30.25, 3.6, 3.0, 4.4, 5)
    for y in (-15, 15):
        if g.detail:
            chamfered(g, (0, y, 11.7), (3.6, 7, .8), shade(body, .78), 1, .15)
            grille(g, 12.1, 12.25, -1.2, 1.2, y - 2.6, y + 2.6, 13)
        else:
            g.box((0, y, 11.7), (3.6, 7, .8), shade(body, .78))  # equipment boxes
            roof_plate(g, 12.25, rect(-1.2, 1.2, y - 2.6, y + 2.6), DARK)
    for y in (-4, 4):
        roof_plate(g, 11.55, rect(-1, 1, y - 1, y + 1), DARK)  # hatches
    if not g.detail:
        return
    # LOD0: hatch lids, the doors' rims, handles and steps, blade antennas and grab irons beside the gangways.
    for y in (-4, 4):
        chamfered(g, (0, y, 11.55), (2.1, 2.1, .3), shade(body, .85), 1, .08)
    for x in (-4.36, 4.36):
        for y in (-27.2, 27.2):
            for points, color in ((rect(y - 1.3, y - 1.2, 4.2, 9.7), DARK), (rect(y + 1.2, y + 1.3, 4.2, 9.7), DARK),
                                  (rect(y - 1.2, y + 1.2, 9.6, 9.7), DARK), (rect(y + .55, y + .75, 6.6, 7.4), STEEL)):
                plate(g, x * 1.003, points, color)
            for z in (2.2, 3.2):
                g.box((x * .92, y, z), (.6, 2.0, .12), RUNNING)
            for dy in (-.95, .95):
                g.beam((x * .975, y + dy, 3.8), (x * .975, y + dy, 2.1), .1, RUNNING, 4)
    for y in (-9.0, 9.0):
        g.box((0, y, 11.75), (.08, .9, .7), DARK)
    for side in (-1, 1):
        for x in (-2.6, 2.6):
            grab(g, (x, side * 30.2, 4.8), (x, side * 30.2, 8.6), (0, side * .25, 0))


