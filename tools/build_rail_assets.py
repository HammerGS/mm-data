def livery(g, body, trim):
    """Declare the Body (1) and Trim (2) slots with these default colours and return them, quantised as stored."""
    presets = [[name, colour_text(value)] for name, value in RAIL_PAINT.items()]
    g.colour_slots = [{'name': name, 'colour': colour_text(RAIL_PAINT[paint]), 'presets': presets}
                      for name, paint in (('Body', body), ('Trim', trim))]
    return [colour(slot['colour']) for slot in g.colour_slots]


def shade(value, factor):
    return tuple(c * factor for c in value)


def unique(points):
    """The points without repeats, so a quad that narrows to a point becomes a triangle."""
    kept = []
    for p in points:
        if all((Vector(p) - Vector(q)).length > 1e-6 for q in kept):
            kept.append(p)
    return kept


def face_out(g, points, color, outward):
    """A flat convex polygon facing along outward (its winding is turned to match)."""
    points = unique(points)
    if len(points) < 3:
        return
    normal = sum((Vector(a).cross(Vector(b)) for a, b in zip(points, points[1:] + points[:1])), Vector())
    g.face(points if normal.dot(Vector(outward)) >= 0 else points[::-1], color)


def rect(u0, u1, v0, v1):
    return [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]


def plate(g, x, points, color):
    """A flat panel on a side wall at x, facing away from the centre line; points are (y, z)."""
    face_out(g, [(x, y, z) for y, z in points], color, (x, 0, 0))


def end_plate(g, y, points, color):
    """A flat panel on an end face at y, facing away from the vehicle's middle; points are (x, z)."""
    face_out(g, [(x, y, z) for x, z in points], color, (0, y, 0))


def roof_plate(g, z, points, color):
    """A flat panel lying at height z, facing up; points are (x, y)."""
    face_out(g, [(x, y, z) for x, y in points], color, (0, 0, 1))


def stripes(g, a0, a1, b0, b1, count, outward, colours=(HAZARD, DARK)):
    """Diagonal warning stripes over the flat quad a0 a1 b1 b0, a its lower edge."""
    def at(p, q, t):
        t = min(1, max(0, t))
        return tuple(u + (v - u) * t for u, v in zip(p, q))
    for i in range(count + 1):
        u0, u1 = i / count, (i + 1) / count
        face_out(g, [at(a0, a1, u0), at(a0, a1, u1), at(b0, b1, u1 - 1 / count), at(b0, b1, u0 - 1 / count)],
                 colours[i % 2], outward)


def end_stripes(g, y, half, z0, z1, count=6):
    """Warning stripes across an end face at y."""
    stripes(g, (-half, y, z0), (half, y, z0), (-half, y, z1), (half, y, z1), count, (0, y, 0))


def chevron(g, x, y, z, size, color, down=False):
    """A chevron on the side wall at x centred on (y, z): '>' pointing +Y, or 'V' pointing down."""
    s, t = size, size * .45
    for side in (1, -1):
        arm = [(-s, side * .8 * s), (-s + t, side * .8 * s), (t, 0), (0, 0)]
        plate(g, x, [(y + v, z - u) if down else (y + u, z + v) for u, v in arm], color)


def loft(g, sections, paint, ends=(None, None)):
    """A body swept along Y through sections [(y, half), ...] with y increasing. A half profile lists the right side's
    (x, z) points from the bottom up and is mirrored onto the left; every section has as many points. paint(segment,
    band) gives the (slot, colour) of the faces between sections segment and segment + 1, or None to leave them out;
    band 0 is the side's lowest edge, len(half) - 1 the roof and -1 the floor. ends are the (slot, colour) of the rear
    (-Y) and front caps, or None; a cap is the convex hull of its section. The faces are flat: every band reads as one
    panel."""
    rings = [[(-x, y, z) for x, z in half] + [(x, y, z) for x, z in reversed(half)] for y, half in sections]
    n = len(sections[0][1])
    bands = list(range(n)) + list(range(n - 2, -1, -1)) + [-1]
    for k in range(len(rings) - 1):
        for e, band in enumerate(bands):
            painted = paint(k, band)
            f = (e + 1) % (2 * n)
            quad = unique([rings[k][e], rings[k][f], rings[k + 1][f], rings[k + 1][e]])
            if painted and len(quad) > 2:
                g.slot = painted[0]
                g.face(quad, painted[1])
    for ring, end, outward in ((rings[0], ends[0], -1), (rings[-1], ends[1], 1)):
        if end:
            g.slot = end[0]
            face_out(g, hull(ring), end[1], (0, outward, 0))
    g.slot = 0


def hull(ring):
    """The convex hull of a section's points (x, y, z) in the X-Z plane, without collinear points."""
    points = sorted({(round(x, 6), round(z, 6)) for x, _, z in ring})
    y = ring[0][1]

    def side(chain):
        kept = []
        for p in chain:
            while len(kept) > 1 and ((kept[-1][0] - kept[-2][0]) * (p[1] - kept[-2][1])
                                     - (kept[-1][1] - kept[-2][1]) * (p[0] - kept[-2][0])) <= 1e-9:
                kept.pop()
            kept.append(p)
        return kept[:-1]
    return [(x, y, z) for x, z in side(points) + side(points[::-1])]


def circle(radius, centre, steps=8):
    """The right half of a 2 * steps-gon about the Y axis at height centre, from the bottom up; its top, bottom and
    sides are flat facets."""
    return [(radius * sin((k + .5) * pi / steps), centre - radius * cos((k + .5) * pi / steps)) for k in range(steps)]


def ring(g, y0, y1, radius, centre, painted, steps=8):
    """A short cylinder about the Y axis (a band round a tank), capped."""
    loft(g, [(y0, circle(radius, centre, steps)), (y1, circle(radius, centre, steps))], lambda k, band: painted,
         (painted, painted))


def tank(g, radius, centre, half, head, shell, heads):
    """A tank along Y: the shell from -half to half and dished heads head long beyond it, (slot, colour) each."""
    profile = ((-half - head, .42), (-half - head * .78, .74), (-half - head * .42, .93), (-half, 1))
    sections = [(y, circle(radius * f, centre)) for y, f in profile]
    sections += [(-y, circle(radius * f, centre)) for y, f in reversed(profile)]
    loft(g, sections, lambda k, band: shell if k == 3 else heads, (heads, heads))


def bogie(g, y, axles=2, wheelbase=4.8):
    """Wheels on the rails, chunky side frames with a spring nest outside them and the bolster under the body. LOD0
    rounds the wheels, adds axles and axle boxes, and opens each side frame between a top and a bottom chord, with
    pedestals over the axles and coil springs in the windows between them."""
    g.slot = 0
    axle = [y + (k / (axles - 1) - .5) * wheelbase for k in range(axles)]
    for at in axle:
        for x in (-2.1, 2.1):
            # An upright cylinder turned onto the axle, so its lowest vertex touches the rail top exactly.
            old = g.transform.copy()
            g.transform = old @ Matrix.Translation((x - .22, at, 1.3)) @ Matrix.Rotation(radians(90), 4, 'Y')
            g.cylinder(0, 0, 0, 1.3, .44, DARK, 12 if g.detail else 8)
            g.transform = old
    if g.detail:
        length = wheelbase + 2.2
        for x in (-2.7, 2.7):
            g.box((x, y, 2.15), (.5, length, .5), RUNNING)  # top chord
            g.box((x, y, 1.3), (.5, length, .4), RUNNING)  # bottom chord
            for k, at in enumerate(axle):
                y0 = at - .8 if k else y - length / 2
                y1 = at + .8 if k < axles - 1 else y + length / 2
                g.box((x, (y0 + y1) / 2, 1.7), (.5, y1 - y0, .4), RUNNING)  # pedestal
                g.box((x * 1.15, at, 1.35), (.3, 1.0, .9), shade(RUNNING, 1.35))  # axle box
            for a, b in zip(axle, axle[1:]):
                for dy in (-.4, .4):
                    g.cylinder(x * 1.04, (a + b) / 2 + dy, 1.5, .2, .4, STEEL, 8)  # coil springs
        for at in axle:
            g.beam((-1.9, at, 1.3), (1.9, at, 1.3), .3, RUNNING, 6)
    else:
        for x in (-2.7, 2.7):
            g.box((x, y, 1.75), (.5, wheelbase + 2.2, 1.3), RUNNING)
            g.box((x * 1.04, y, 1.65), (.5, 1.6, 1.1), DARK)  # spring nest, under the frame's top
    g.box((0, y, 2.6), (5.8, 1.8, .8), RUNNING)


def couplers(g, length, front=True):
    g.slot = 0
    for side in (-1, 1) if front else (-1,):
        if g.detail:
            # A knuckle coupler on its shank, the knuckle's pin and two air hoses hanging beside it.
            end = side * length / 2
            g.box((0, end - side * 1.05, 2.5), (.55, .7, .5), DARK)
            chamfered(g, (0, end - side * .35, 2.5), (1, .7, .8), DARK, 0, .15)
            g.cylinder(.22, end - side * .35, 2.9, .12, .12, STEEL, 6)
            for x in (-.85, .85):
                g.beam((x, end - side * 1.3, 2.75), (x * 1.1, end - side * .55, 1.85), .2, DARK, 4)
        else:
            g.box((0, side * (length / 2 - .7), 2.5), (1, 1.4, .8), DARK)


def skirt(g, y0, y1, half, painted):
    """A fairing under the body (a fuel tank, an equipment skirt), its ends ramped up into the floor."""
    end = [(x * .85, z + (half[-1][1] - z) * .45) for x, z in half]
    loft(g, [(y0, end), (y0 + 1, half), (y1 - 1, half), (y1, end)],
         lambda k, band: None if band == len(half) - 1 else painted, (painted, painted))


def railing(g, x, y0, y1, base, color, posts=3, height=2.4):
    """A handrail at x from y0 to y1, height above base, on posts; LOD0 adds a knee rail and a post between each two."""
    for h in (height, height / 2) if g.detail else (height,):
        g.beam((x, y0, base + h), (x, y1, base + h), .16, color, 3)
    count = 2 * posts - 1 if g.detail else posts
    for k in range(count):
        y = y0 + (y1 - y0) * k / (count - 1)
        g.beam((x, y, base), (x, y, base + height), .16, color, 3)


def ladder(g, x, y, z0, z1, color, rungs=4, across=(0, .45)):
    """Two rails at (x, y) -/+ across, rungs between them; LOD0 has twice the rungs and one more."""
    ax, ay = across
    for side in (-1, 1):
        g.beam((x + side * ax, y + side * ay, z0), (x + side * ax, y + side * ay, z1), .14, color, 3)
    count = 2 * rungs + 1 if g.detail else rungs
    for k in range(1, count + 1):
        z = z0 + (z1 - z0) * k / (count + 1)
        g.beam((x - ax, y - ay, z), (x + ax, y + ay, z), .12, color, 3)


def beacon(g, x, y, z):
    if g.detail:
        # A dark base and cap round a rounder lens.
        g.cylinder(x, y, z, .4, .12, DARK, 12)
        g.cylinder(x, y, z + .12, .34, .3, AMBER, 12)
        g.cylinder(x, y, z + .42, .2, .13, DARK, 12)
    else:
        g.cylinder(x, y, z, .4, .55, AMBER, 8)


def fan(g, y, z, radius=1.4):
    """A roof fan: a dark disc and its hub, lying just above the roof at z. LOD0 sets it in a shroud with blades."""
    if not g.detail:
        for r, lift, color in ((radius, .15, DARK), (radius * .35, .3, STEEL)):
            face_out(g, [(r * cos(k * pi / 4), y + r * sin(k * pi / 4), z + lift) for k in range(8)], color, (0, 0, 1))
        return
    g.ring(0, y, z, radius, radius - .16, .4, RUNNING, 16)
    inner = radius - .16
    face_out(g, [(inner * cos(k * pi / 8), y + inner * sin(k * pi / 8), z + .12) for k in range(16)], DARK, (0, 0, 1))
    for k in range(6):
        a = k * pi / 3
        root, tip = Vector((cos(a), sin(a), 0)) * .3, Vector((cos(a), sin(a), 0)) * (inner - .08)
        across = Vector((-sin(a), cos(a), 0)) * .22
        face_out(g, [Vector((0, y, z + .22)) + p for p in (root - across, tip - across)]
                 + [Vector((0, y, z + .3)) + p for p in (tip + across, root + across)], STEEL, (0, 0, 1))
    g.cylinder(0, y, z + .12, .3, .28, DARK, 8)


def bezel(g, y, x0, x1, z0, z1):
    """LOD0: a dark housing behind a lamp on the end face at y (the lamp lies 0.05 beyond the face) and a visor."""
    facing = 1 if y > 0 else -1
    end_plate(g, y + facing * .02, rect(x0 - .15, x1 + .15, z0 - .15, z1 + .15), DARK)
    g.box(((x0 + x1) / 2, y + facing * .2, z1 + .2), (x1 - x0 + .3, .4, .1), DARK)


def grab(g, a, b, out, color=STEEL):
    """LOD0: a grab iron from a to b standing off its wall by out."""
    a, b, out = Vector(a), Vector(b), Vector(out)
    for p, q in ((a, a + out), (a + out, b + out), (b + out, b)):
        g.beam(p, q, .1, color, 4)


def brake_wheel(g, x, y, z, low):
    """LOD0: a hand brake wheel on the end face at y, its staff down to low."""
    facing = 1 if y > 0 else -1
    g.beam((x, y, z), (x, y + facing * .15, z), 1.4, DARK, 12)
    g.beam((x, y + facing * .08, z), (x, y + facing * .08, low), .14, DARK, 4)


def end_rail(g, y, half, base, color, height=1.6):
    """LOD0: a handrail across an end platform at y on three posts."""
    g.beam((-half, y, base + height), (half, y, base + height), .14, color, 3)
    for x in (-half, 0, half):
        g.beam((x, y, base), (x, y, base + height), .14, color, 3)


def grille(g, z0, z1, x0, x1, y0, y1, count, colours=(DARK, RUNNING)):
    """LOD0 for a dark roof plate floating at z1 over a roof at z0: count slats across Y in alternating colours, on a
    rim down to the roof."""
    for k in range(count):
        roof_plate(g, z1, rect(x0, x1, y0 + (y1 - y0) * k / count, y0 + (y1 - y0) * (k + 1) / count), colours[k % 2])
    for (u0, v0), (u1, v1) in (((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x1, y1), (x0, y1)), ((x0, y1), (x0, y0))):
        face_out(g, [(u0, v0, z0), (u1, v1, z0), (u1, v1, z1), (u0, v0, z1)], RUNNING,
                 ((u0 + u1) / 2 - (x0 + x1) / 2, (v0 + v1) / 2 - (y0 + y1) / 2, 0))


def bellows(g, y0, y1, width, z0, z1, folds=4):
    """LOD0 for a gangway box: its folds, every other one inset and lighter."""
    step = (y1 - y0) / folds
    for k in range(folds):
        inset = .2 * (k % 2)
        g.box((0, y0 + step * (k + .5), (z0 + z1) / 2), (width - inset, step, z1 - z0 - inset),
              shade(DARK, 1 + .5 * (k % 2)))


def brake_gear(g, y, z, length=7.0):
    """LOD0: an air reservoir and a brake cylinder hanging under the frame, centred at y."""
    g.beam((1.3, y - length / 2, z), (1.3, y + length / 2, z), 1.0, DARK, 8)
    g.beam((-1.4, y - 1.2, z + .1), (-1.4, y + 1.2, z + .1), .8, RUNNING, 8)


def plough(g, back, tip, half, z0=.5, z1=3.6):
    """A wedge snow plough pointing +Y with warning stripes on its two blades."""
    for side in (-1, 1):
        stripes(g, (0, tip, z0), (side * half, back, z0), (0, tip - 1.2, z1), (side * half, back - 1.0, z1), 5,
                (side, 1.4, .3))
        face_out(g, [(side * half, back, z0), (side * half, back - 1.0, z1), (side * half, back - 1.0, z0)], DARK,
                 (side, 0, 0))
    face_out(g, [(0, tip - 1.2, z1), (half, back - 1.0, z1), (-half, back - 1.0, z1)], DARK, (0, 0, 1))
    face_out(g, [(x, back - 1.0, z) for x, z in rect(-half, half, z0, z1)], DARK, (0, -1, 0))


def flatcar(g, length, deck, belly, painted):
    """A flat underframe the length of the car between its headstocks: sides painted (slot, colour), a dark deck at
    height deck, deepened to belly between the bogies (a fish-belly frame), warning stripes on both ends."""
    half, low = length / 2 - 1.2, deck - 1.2
    profile = lambda z: [(4.4, z), (4.4, deck)]
    loft(g, [(-half, profile(low)), (-half + 9, profile(low)), (-half + 13, profile(belly)),
             (half - 13, profile(belly)), (half - 9, profile(low)), (half, profile(low))],
         lambda k, band: (0, DARK) if band == -1 else (0, DECK) if band == 1 else painted, (painted, painted))
    for side in (-1, 1):
        end_stripes(g, side * (half + .05), 4.4, low, deck)
    if g.detail:
        # LOD0: plank seams across the deck, stirrup steps under the corners and a brake staff at the -Y end.
        count = round(2 * half / 1.6)
        for k in range(1, count):
            y = -half + k * 2 * half / count
            roof_plate(g, deck + .12, rect(-4.3, 4.3, y - .05, y + .05), shade(DECK, .55))
        for side in (-1, 1):
            for x in (-3.9, 3.9):
                grab(g, (x, side * (half - 1.0), low), (x, side * (half - .2), low), (0, 0, -.9), RUNNING)
        g.beam((3.0, -(half - .4), deck), (3.0, -(half - .4), deck + 2.4), .14, DARK, 4)
        g.cylinder(3.0, -(half - .4), deck + 2.4, .6, .1, DARK, 12)


def heap(g, y0, y1, width, base, peak, seed):
    """A rough heap of ore along Y over a load surface at base, about peak high; its facets lighten towards the top."""
    rng = random.Random(seed)
    count = max(4, round((y1 - y0) / 2.0))
    sections = []
    for k in range(count + 1):
        t = k / count
        h = peak * min(1, 5 * t * (1 - t) + .2) * rng.uniform(.6, 1.1) if 0 < k < count else .3
        w, lean = width * rng.uniform(.95, 1), rng.uniform(-.6, .6)
        sections.append((y0 + (y1 - y0) * t, [(w, base), (w * .8, base + h * .5), (w * .45 + lean, base + h * .9),
                                               (max(.1, w * .12 + lean), base + h)]))
    loft(g, sections, lambda k, band: None if band == -1 else (0, shade(ORE, (.8, 1, 1.25, 1.5)[band])),
         ((0, ORE), (0, ORE)))


def armour(zb, side, top, shoulder, roof):
    """A seven-point armoured body profile: a bevelled skirt foot at zb, the stripe from 5.6 to 6.4, the side up to
    (side, top) and a chamfered shoulder and roof edge."""
    return [(side - .25, zb), (side, zb + .7), (side, 5.6), (side, 6.4), (side - .05, top), shoulder, roof]


