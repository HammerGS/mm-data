def hopper(g, length, top, ends, braced, body, trim, seed):
    """An open hopper car heaped with ore: sloped end sheets down to a flat floor, a rim round the top (Trim), ribs or
    diagonal braces on the sides (braced), discharge chutes underneath and striped headstocks."""
    half, flat, load = length / 2 - 1.4, length / 2 - 5.4, top - .8
    wall = lambda z: [(4.4, z), (4.4, top), (3.95, top), (3.95, load)]
    paints = {0: (1, body), 1: (2, trim), 2: (1, shade(body, .5)), 3: (0, ORE), -1: (1, shade(body, .7))}
    loft(g, [(-half, wall(ends)), (-flat, wall(4.6)), (flat, wall(4.6)), (half, wall(ends))],
         lambda k, band: paints[band])
    for side in (-1, 1):
        end_plate(g, side * half, rect(-4.4, 4.4, ends, top), shade(body, .8))
        face_out(g, [(x, side * (half - .02), z) for x, z in rect(-3.95, 3.95, load, top)], shade(body, .5),
                 (0, -side, 0))
        g.box((0, side * (length / 2 - 1.0), 3.5), (8.4, .8, 1.2), DECK)  # headstocks
        end_stripes(g, side * (length / 2 - .55), 4.2, 2.9, 4.1)
        g.box((0, side * flat / 2, 3.7), (5.0, flat * .6, 1.8), DARK)  # discharge chutes
    g.box((0, 0, 3.85), (1.8, length - 3, 1.2), DECK)  # centre sill, under the chutes' tops
    heap(g, -half + .8, half - .8, 3.9, load, 2.6, seed)
    g.slot = 1
    for x in (-4.5, 4.5):
        if braced:
            posts = [-flat + k * flat / 2 for k in range(5)]
            for y in posts:
                g.beam((x, y, 4.6), (x, y, top - .3), .5, shade(body, .72), 4)
            for y0, y1 in zip(posts, posts[1:]):
                for a, b in ((y0, (y0 + y1) / 2), (y1, (y0 + y1) / 2)):
                    g.beam((x, a, top - .4), (x, b, 5.0), .45, shade(body, .72), 4)
        else:
            for k in range(-3, 4):
                g.box((x, k * 4.0, (4.3 + top) / 2), (.3, .5, top - 4.9), shade(body, .72))
    g.slot = 0
    if not g.detail:
        return
    # LOD0: ladders up the end sheets, the chutes' door levers, a brake wheel and the brake gear.
    for side in (-1, 1):
        ladder(g, side * 2.8, side * (half + .25), 4.15, top - .1, RUNNING, 4, (.4, 0))
        for x in (-2.55, 2.55):
            g.beam((x, side * flat / 2 - 1.2, 3.0), (x, side * flat / 2 + 1.2, 4.2), .18, STEEL, 4)
    brake_wheel(g, 2.0, -(half + .05), top - 2.2, 4.6)
    brake_gear(g, 0, 2.4, 5.0)


