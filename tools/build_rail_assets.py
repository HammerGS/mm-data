"""Build the rail pieces that never bend (scenery/rail/): the buffer stop, the rolling stock of three families, and the
three train stamps' rows (layouts.json) with their palette thumbnails.

Run with Blender: blender --background --factory-startup --python tools/build_rail_assets.py
The track itself (ballast bed, sleepers, rails) is generated by the client's route builder shared with the maglev
beam, so that it follows the ground, slopes and bridge decks; the level-crossing signal is a palette object of
build_scenery_assets.py.

Units are board px: a hex is 84 x 72 (about 30 m, so 2.8 px per metre) and a level is 18. The generated track's
profile: ballast 11.2 wide with its top 0.6 above the carrier plane (ground or deck), sleepers 0.3 thick on it, rails
0.5 x 0.5 at +/-2.1 (gauge 4.2, standard gauge), so the rail top lies RAIL_TOP = 1.4 above the carrier plane.
Every piece here has its origin on the track's centre line at rail-top height (the wheels touch Z = 0) with the track
along Y: a piece placed RAIL_TOP above the track's carrier plane rides the rails. The vehicles are real scale; a
vehicle's LENGTH is over its coupler faces (a power car's nose tip counts as one), so coupled vehicles stand
LENGTH[a]/2 + LENGTH[b]/2 apart. Every vehicle carries its own couplers, so no coupler piece is needed. Locomotive and
power car noses and the buffer stop's buffers face +Y. Vehicles have two colour slots, Body and Trim, for liveries;
every livery colour is a preset of both. Warning stripes, lamps, glass and running gear are fixed colours.

The families: Frontier Rail (armoured military-industrial freight and an armoured coach, olive and orange), the Express
(a high-speed power car and its passenger car, white with a coloured stripe) and Ironline (colony mining freight, red
and cream).

Levels: a vehicle's GLB holds two levels (build_maglev_assets.export_levels: root groups <name>-lod0 and -lod1). LOD1
is the plain mesh; LOD0 is the same function drawn with g.detail set, which adds close-up detail within DETAIL_BUDGET
triangles: open bogie frames with coil springs, axle boxes and axles, knuckle couplers with air hoses, double handrails,
ladders, grab irons, brake wheels, lamp housings, beacons, slatted grilles and fans, bevelled hatches, gratings and
underframe equipment. LOD0 keeps LOD1's bounds and touches the rails as it does. The buffer stop keeps one level.
"""
