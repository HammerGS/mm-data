def git(*args):
    return subprocess.run(['git', *args], cwd=ROOT, check=True, capture_output=True).stdout


def decal(asset):
    return asset.startswith('decal/')


def meshed(asset):
    """A row asset with a GLB of its own: not the shared tree, paint or a generated route."""
    return asset != TREE and not decal(asset) and asset not in GENERATED


def reauthored(key):
    """Maglev keys decode to a route marker and pieces measured from the sprites, not to their old rows. The rail train
    stamps are palette compositions (tools/build_rail_assets.py) with no legacy key, like the maglev one."""
    return 'maglev' in key or key in RAIL_STAMPS


class Source:
    """GLBs and layouts at one revision: the working tree (base None) or a commit."""

    def __init__(self, base, scratch):
        self.base, self.scratch, self.cache = base, scratch, {}
        self.blobs = {}
        if base:
            for line in git('ls-tree', '-r', base, BOARD + '/scenery').decode().splitlines():
                meta, path = line.split('\t')
                self.blobs[path] = meta.split()[2]

    def path(self, asset):
        return f'{BOARD}/{asset}.glb'

    def exists(self, asset):
        return self.path(asset) in self.blobs if self.base else (ROOT / self.path(asset)).is_file()

    def layouts(self):
        path = BOARD + '/scenery/layouts.json'
        return json.loads(git('show', f'{self.base}:{path}') if self.base else (ROOT / path).read_bytes())

    def points(self, asset):
        if asset not in self.cache:
            file = ROOT / self.path(asset)
            if self.base:
                file = Path(self.scratch) / self.base / self.path(asset)
                file.parent.mkdir(parents=True, exist_ok=True)
                file.write_bytes(git('show', f'{self.base}:{self.path(asset)}'))
            data = read_glb(file)
            assert all(not any(n.get('translation', [0])) and 'rotation' not in n and 'scale' not in n
                       for n in data['nodes']), 'Expected untransformed nodes: ' + asset
            values = np.concatenate([np.array(m['vertices']).reshape(-1, 12) for m in data['meshes']])
            slots = np.concatenate([m.get('slots', [0] * (len(m['vertices']) // 12)) for m in data['meshes']])
            self.cache[asset] = values[:, :3], values[:, 6:9], slots.astype(int), data['extras'].get('mmColourSlots', [])
        return self.cache[asset][0]

    def painted(self, asset, colours):
        """The mesh's display vertex colours with its colour slots replaced by `colours` (a row's)."""
        self.points(asset)
        _, values, slots, defaults = self.cache[asset]
        values = values.copy()
        for index in np.nonzero(slots)[0] if colours else ():
            slot = slots[index] - 1
            if slot < len(colours) and colours[slot]:
                values[index] = recolour(values[index], colour(defaults[slot]['colour']), colour(colours[slot]))
        return values

    def slot_count(self, asset):
        self.points(asset)
        return len(self.cache[asset][3])

    def triangles(self, asset):
        """The working tree's triangles of one mesh, (T, 3, 3) in model px, and a shade per triangle.

        Equal shades render identically wherever they overlap: one untextured material and vertex colour.
        Every textured triangle gets a shade of its own.
        """
        data = read_glb(ROOT / self.path(asset))
        materials = {p['meshpartid']: p['materialid'] for n in data['nodes'] for p in n['parts']}
        textured = {m['id'] for m in data['materials'] if m.get('textures')}
        result, shades = [], []
        for mesh in data['meshes']:
            values = np.array(mesh['vertices']).reshape(-1, 12)
            for part in mesh['parts']:
                corners = np.array(part['indices']).reshape(-1, 3)
                result.append(values[corners, :3])
                material = materials.get(part['id'], part['id'])
                for colour in values[corners, 6:9].mean(1).round(3):
                    key = None if material in textured else (material, *colour)
                    shades.append(SHADES.setdefault(key, len(SHADES)) if key else -1 - len(shades))
        if not result: return np.zeros((0, 3, 3)), np.zeros(0, int)
        return np.concatenate(result), np.array(shades)


def blob(path):
    data = path.read_bytes()
    return hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()


def fix(key):
    return next((value for pattern, value in FIXES.items() if re.fullmatch(pattern, key)), None)


def stretch(row):
    """A row's per-axis factors on the mesh's own axes, applied before its turn."""
    return np.array(row.get('stretch', [1, 1, 1]), float)


def turn(row):
    t = np.radians(row['rotation']); c, s = np.cos(t), np.sin(t)
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


def compose(rows, source):
    parts = []
    for row in rows:
        if not meshed(row['asset']): continue
        parts.append(source.points(row['asset']) * stretch(row) * row['scale'] @ turn(row).T + row['position'])
    return np.concatenate(parts) if parts else np.zeros((0, 3))


def tinted(rows, source):
    """The display colours of compose()'s vertices, in its order."""
    parts = [source.painted(row['asset'], row.get('colours')) for row in rows
             if meshed(row['asset'])]
    return np.concatenate(parts) if parts else np.zeros((0, 3))


def placed(rows, source):
    """Each non-tree row's triangles in the layout's frame, with their shades and the row index as label."""
    parts, shades, labels = [], [], []
    for index, row in enumerate(rows):
        if not meshed(row['asset']): continue
        triangles, shade = source.triangles(row['asset'])
        parts.append(triangles * stretch(row) * row['scale'] @ turn(row).T + row['position'])
        shades.append(shade); labels.append(np.full(len(triangles), index))
    if not parts: return np.zeros((0, 3, 3)), np.zeros(0, int), np.zeros(0, int)
    return np.concatenate(parts), np.concatenate(shades), np.concatenate(labels)


def overlaps(triangles, shades, labels, across):
    """Pairs of same-facing, differently shaded triangles closer than COPLANAR px whose outlines overlap: they z-fight.

    across=True keeps only pairs with different labels (rows), False only pairs within one label (mesh).
    Only upward faces count: the board camera looks down, and the check compares their XY outlines.
    """
    a, b, c = triangles[:, 0], triangles[:, 1], triangles[:, 2]
    normal = np.cross(b - a, c - a); area = np.linalg.norm(normal, axis=1)
    keep = area > 1e-6
    normal[keep] /= area[keep, None]
    keep &= normal[:, 2] > .5
    index = np.nonzero(keep)[0]
    offset = (normal * a).sum(1)
    # Same-facing normals (dot > PARALLEL) differ by < .045 per axis: a triangle is filed in every
    # cell within that reach of its normal and looked up in its own cell.
    cells = defaultdict(list)
    scaled = normal * 8
    signs = np.array(list(np.ndindex(2, 2, 2))) * 2 - 1
    for i in index:
        for corner in {tuple(cell) for cell in np.floor(scaled[i] + signs * .36).astype(int)}:
            cells[corner].append(i)
    low, high = triangles.min(1) - COPLANAR, triangles.max(1) + COPLANAR
    found = set()
    for i in index:
        others = np.array(cells[tuple(np.floor(scaled[i]).astype(int))])
        others = others[others > i]
        others = others[(labels[others] != labels[i]) if across else (labels[others] == labels[i])]
        others = others[(normal[others] @ normal[i] > PARALLEL) & (abs(offset[others] - offset[i]) < COPLANAR)
                        & (shades[others] != shades[i])]
        others = others[np.all((low[others] <= high[i]) & (high[others] >= low[i]), axis=1)]
        if len(others) == 0: continue
        # Separating axes in the plane of triangle i: its edge normals and the other triangle's.
        u = triangles[i, 1] - triangles[i, 0]; u /= np.linalg.norm(u); v = np.cross(normal[i], u)
        flat = lambda t: np.stack([t @ u, t @ v], -1)
        mine, theirs = flat(triangles[i]), flat(triangles[others])
        def edges(t):
            d = np.roll(t, -1, -2) - t
            return np.stack([d[..., 1], -d[..., 0]], -1) / np.maximum(np.linalg.norm(d, axis=-1), 1e-9)[..., None]
        axes = np.concatenate([np.broadcast_to(edges(mine), theirs.shape), edges(theirs)], 1)
        p = np.einsum('kad,vd->kav', axes, mine); q = np.einsum('kad,kvd->kav', axes, theirs)
        depth = np.minimum(p.max(2), q.max(2)) - np.maximum(p.min(2), q.min(2))
        for j in others[(depth > OVERLAP).all(1)]: found.add((i, int(j)))
    return found


def copy_signature(file):
    """What a rotated or mirrored copy shares: its vertices' radii about Z, heights and colours (as a multiset, so a
    hexagon and a circle of the same radius differ), and its materials."""
    data = read_glb(file)
    values = np.concatenate([np.array(m['vertices']).reshape(-1, 12) for m in data['meshes']])
    rows = np.column_stack([np.hypot(values[:, 0], values[:, 1]), values[:, 2], values[:, 6:10]]).round(3) + 0.
    materials = sorted((m['id'], *sorted(t.get('filename', '') for t in m.get('textures', []))) for m in data['materials'])
    rows = rows[np.lexsort(rows.T[::-1])]
    return hashlib.sha1(rows.tobytes() + repr(materials).encode()).hexdigest()


def trees(rows):
    return [(*row['position'], row['rotation'], row['scale']) for row in rows if row['asset'] == TREE]


def tree_residual(old, new):
    if len(old) != len(new): return float('inf')
    worst = 0
    for a, b in zip(old, new):
        turn = abs((a[3] - b[3] + 180) % 360 - 180)
        worst = max(worst, turn, *(abs(x - y) for x, y in zip(a[:3] + a[4:], b[:3] + b[4:])))
    return worst


def hausdorff(a, b):
    if len(a) == 0 or len(b) == 0: return 0 if len(a) == len(b) else float('inf')
    # Matched vertex order bounds the distance; a renamed mesh needs no all-pairs search.
    if a.shape == b.shape and (matched := np.sqrt(((a - b) ** 2).sum(1)).max()) <= TOLERANCE: return matched
    def directed(p, q):
        worst = 0
        for i in range(0, len(p), 1024):
            d = ((p[i:i + 1024, None, :] - q[None, :, :]) ** 2).sum(-1).min(1)
            worst = max(worst, d.max())
        return worst ** .5
    return max(directed(a, b), directed(b, a))


def grounded(points):
    return points - [0, 0, points[:, 2].min()] if len(points) else points


def key_of(image):
    """A tileset image's legacy scenery key, without a crop suffix."""
    return 'scenery/' + Path(re.sub(r'\([^)]*\)$', '', image)).with_suffix('').as_posix()


def family(key):
    stem = key.split('/')[-1]
    return re.sub(r'(?<=[A-Za-z_-])\d+$|(?<=-)\d+-\d+$|(?<=OrbitalGun)[ENSW]$', '#', stem).replace('FluffSystem-', '')


def check_decals(layouts, assets, tileset):
    """Check 8. Returns (failures, summary lines)."""
    from PIL import Image
    import build_board_decals as built
    failures = []
    folder = ROOT / BOARD / 'decals'
    data = json.loads((folder / 'decals.json').read_text(encoding='utf-8'))
    decals, legacy = data['decals'], data['legacy']
    for asset, entry in decals.items():
        image = folder / (asset[len('decal/'):] + '.png')
        if not re.fullmatch(r'decal/[a-z0-9-]+/[a-z0-9-]+', asset) or not image.is_file():
            failures.append(f'{asset}: no image at decals/{asset[len("decal/"):]}.png'); continue
        width, height = entry['size']
        with Image.open(image) as opened:
            if abs(opened.width / opened.height * height / width - 1) > .01:
                failures.append(f'{asset}: image aspect differs from its size')
    for path in folder.rglob('*.png'):
        if 'decal/' + path.relative_to(folder).with_suffix('').as_posix() not in decals:
            failures.append(f'{path.relative_to(folder).as_posix()}: image without a decals.json entry')
    failures += [f'{a["id"]}: palette decal not in decals.json' for a in assets if a['kind'] == 'decal' and a['id'] not in decals]
    failures += [f'{old}: decodes to a missing decal' for old, entry in legacy.items()
                 if entry['decal'] not in decals or old in decals]
    images = {'decal/' + Path(r['image']).with_suffix('').as_posix() for r in tileset
              if r['image'] and DECAL_IMAGES.fullmatch(r['image'])}
    symbols = {key for key in images if key.startswith('decal/saxarba/SMV_GroundSymbols/')}
    failures += [f'{key}: legacy decal image without a decode entry' for key in sorted(images - set(legacy))]
    owned = {key_of(r['image']) for r in tileset if r['image'] and DECAL_ROW_IMAGES.fullmatch(r['image'])}
    failures += [f'{key}: terrain image without its decal row' for key in sorted(owned)
                 if not layouts.get(key) or not all(decal(r['asset']) for r in layouts[key])]
    sets = defaultdict(list)
    for entry in legacy.values():
        if entry.get('set'): sets[entry['decal']].append(entry.get('direction', -1))
    failures += [f'{asset}: set pieces {sorted(d)}' for asset, d in sets.items() if sorted(d) != list(range(-1, 6))]
    emblems = [asset for asset in sets if asset.startswith('decal/emblems/')]
    # Each one-hex variant is its emblem scaled and turned by the decode entry (blurred |difference|, 0..255).
    errors, large, overlaps = [], [], []
    for prefix, name in built.EMBLEMS.items():
        emblem = built.premultiplied(folder / f'emblems/{name}.png')
        for variant in range(1, 7):
            key = f'{built.LEGACY_SYMBOLS}{prefix}-{variant:02d}'
            entry = legacy[key]
            error = built.single_error(emblem, prefix, variant, entry['scale'], entry['rotation'])
            rendered = built.render(emblem, entry['scale'], entry['rotation'])[..., 3] > .5
            target = built.premultiplied(built.SYMBOLS / f'{prefix}-{variant:02d}.png')[..., 3] > .5
            overlap = (rendered & target).sum() / (rendered | target).sum()
            errors.append(error); overlaps.append(overlap)
            if variant == 4: large.append(error)
            if error > 8 or overlap < .75: failures.append(f'{key}: differs from its emblem ({error:.1f}, overlap {overlap:.2f})')
    # Every car of a car-park key has its own slot on one of the key's decal rows.
    seated, keys, plates_total = 0, 0, 0
    for key, rows in layouts.items():
        plates = [r for r in rows if decal(r['asset'])]
        seats = [tuple(r['seat']) for r in rows if 'seat' in r]
        if re.fullmatch(r'scenery/fluff/cars_\w+', key):
            keys += 1; plates_total += len(plates)
            if not plates or any('seat' not in r for r in rows if built.CAR_ROW.match(r['asset'])):
                failures.append(f'{key}: a car without a seat')
        if len(set(seats)) != len(seats): failures.append(f'{key}: two cars share a slot')
        failures += [f'{key}: seat {i}, {j} names no slot' for i, j in seats
                     if i >= len(plates) or j >= len(decals.get(plates[i]['asset'], {}).get('slots', []))]
        seated += len(seats)
    lines = [f'- Decals: {len(decals)} in `decals/decals.json`, each with its image by path convention; '
             f'{len(legacy)} legacy decal ids decode to them.',
             f'- Emblems: {len(emblems)} full emblems; all {len(symbols)} ground-symbol tiles decode ({len(emblems)} sets of 7 '
             f'pieces, {len(errors)} one-hex variants). The variants match their emblem at the decode transform: '
             f'blurred mean |difference| at most {max(errors):.1f}/255 (the -04 variants at most {max(large):.1f}), '
             f'coverage overlap at least {min(overlaps):.2f}.',
             f'- Car parks: {keys} legacy car-park keys place {plates_total} standard decal rows and seat all {seated} '
             'cars in distinct slots (only the conversion places them; no 3D view draws the legacy sprite).',
             f'- Painted families: all {len(images)} ground-symbol, landing-pad, letter, runway and court images have a '
             f'legacy decal id ({len(sets) - len(emblems)} DropShip pads are sets of 7 pieces like the emblems); the '
             f'{len(owned)} elevator-plate and cleared-rubble-gravel images decode to one decal row each.']
    return failures, lines


def imported(terrain):
    """The decode plan's token rule, applied to one tileset selector."""
    levels = {}
    for part in terrain.split(';'):
        bits = part.split(':')
        levels[bits[0]] = bits[1] if len(bits) > 1 else '*'
    fluff = levels.get('fluff', '*')
    if fluff.isdigit() and int(fluff) < 2000: return True
    if levels.get('road_fluff') == '3': return True
    return levels.get('road') == '2' and 'fluff' not in levels and 'road_fluff' not in levels


