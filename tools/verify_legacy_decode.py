"""Prove the legacy scenery decode data in data/models/board/scenery/layouts.json.

The base commit's runtime grounded a whole legacy SCENERY mesh (subtracted its lowest
point) but placed layout rows as authored. Meshes now live under topic folders
(roofs/, parks/, ...), never at a legacy key, so every legacy key decodes through rows:
1. a key whose baked GLB was replaced by rows (one row when it was a plain rename)
   reproduces that grounded GLB;
2. a key that already had rows reproduces its old composition, trees included, except the
   maglev keys, re-authored from their sprites (route marker, direction, cars, ride height); a tileset
   key whose art the base only painted (rails, heli pads, elevator plates, gravel) has no 3D reference;
3. every tileset key that resolved to 3D at the base still resolves, through layouts.json,
   and every row names an existing mesh (a rail route marker's track is generated by the client);
4. every mesh a decoded tileset token turns into stands on Z=0 and has a blueprint entry;
5. rows have Z=0;
6. no layout z-fights: no two same-facing, differently shaded upward surfaces of its rows, or of
   one mesh, lie within COPLANAR px of each other where their outlines overlap;
7. no two meshes that rows, palette props or the scatter kit reach are copies of each other: the
   same vertices about the Z axis (radius, height), colours and materials, so a rotated or mirrored
   copy is caught and a colour variant is not. A copy should be a row on the other mesh (with a
   rotation, mirror or stretch). Stretched and regenerated near-copies are not caught; they need a
   scan with fitted transforms (see the duplicate scan in the decode plan).
8. decals (decals/decals.json, tools/build_board_decals.py): every decal has its image by path convention
   and every image an entry; palette decals and legacy decal ids name existing decals; every legacy
   ground symbol, landing pad, letter, runway marking and court decodes to a decal, every elevator plate
   and the cleared-rubble gravel to a decal row, each emblem's set has its centre and six directions once, and each one-hex
   variant matches its emblem at its decode transform; every car of a car-park key sits in its own slot
   of one of the key's decal rows.
9. colours: a row's optional "colours" (at most 4, '#rrggbb' or null) replace its mesh's colour slots
   (glb_geometry.recolour; the mesh's extras define as many slots as the row names), and a key whose
   rows recolour a mesh reproduces the colours it had at the base, vertex by vertex, within COLOURS/255.
Residuals are symmetric Hausdorff distances between vertex sets, in model px. FIXES lists the
deliberate geometry changes since the base; decal rows (decal/...) are paint and rail route markers
(GENERATED) are built by the client, not meshes. A row's
optional "stretch" [x, y, z] (positive) scales the mesh's own axes before its turn, on top of "scale".

    python tools/verify_legacy_decode.py [--base <commit>]

--base is the last commit with the baked GLBs. Prints the Markdown table kept in
data/models/board/README.md and exits with 1 on any failure. Needs NumPy.
"""
